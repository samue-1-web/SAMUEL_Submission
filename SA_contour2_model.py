def encode_n(n, num_freqs=4):

    freqs = [2 ** i for i in range(num_freqs)]

    feats = []

    for f in freqs:

        feats.append(np.sin(n / f))
        feats.append(np.cos(n / f))

    return np.array(feats, dtype=np.float32)